#!/usr/bin/env python3
# Generate Go bitmap font data for pcat2d from a Windows CJK font.
# Output: font_data.go with font12 / font16 maps (fixed-cell monospace bitmaps).
import os
import sys
from PIL import Image, ImageDraw, ImageFont

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font_data.go")

CJK = (
    "系统信息电池电压流功率剩余温度风扇转速屏幕测试页面按键翻亮唤醒超时网络无线有线"
    "速率信号强度模块版本内存时间运行负载状态开关充电放电满未连接已连接下一当前第页"
    "欢迎数据获取等待输入输出电源硬软名称序列号光衰传感移动触发短长按双击频率刷新色彩"
    "红绿蓝白黑黄青紫方向偏移坐标横竖像素分辨主频内核构建日期通信型号运营商蜂窝流量"
    "当月当日上下行实时累计清零每月初重置计划任务定时模式智静音手动阈值上限百分比限制"
    "报警保护外接扩展卡槽位预留充电宝检测是否固件文件读取错误失败成功处理中请稍候载入"
    "设置关闭打开启用禁用连接正常异常最大最小平均总计共约万千兆字节秒分时天周月年"
    "无线网卡有线以太模块总线芯片驱动设备节点接口协议固件升级重启关机复位恢复出厂"
)

CHARS = set(CJK)
# ASCII printable + common punctuation
for c in range(0x20, 0x7F):
    CHARS.add(chr(c))
for c in "°％±×·—…“”‘’（）【】《》，。：；！？％":
    CHARS.add(c)

FALLBACK_FONTS = [
    r"C:\Windows\Fonts\msyh.ttc",
    r"C:\Windows\Fonts\msyh.ttf",
    r"C:\Windows\Fonts\simhei.ttf",
    r"C:\Windows\Fonts\simsun.ttc",
    r"C:\Windows\Fonts\Deng.ttf",
    r"C:\Windows\Fonts\segoeui.ttf",
]

def pick_font():
    for p in FALLBACK_FONTS:
        if os.path.exists(p):
            return p
    raise SystemExit("no usable font found")

def render_char(font, ch, cell_w, cell_h, size):
    # Render into fixed cell, centered, with 1px top margin
    img = Image.new("L", (cell_w, cell_h), 0)
    d = ImageDraw.Draw(img)
    try:
        d.text((cell_w / 2, cell_h / 2 + 1), ch, fill=255, font=font, anchor="mm")
    except Exception:
        d.text((0, 0), ch, fill=255, font=font)
    rows = []
    for y in range(cell_h):
        bits = 0
        for x in range(cell_w):
            if img.getpixel((x, y)) >= 96:
                bits |= 1 << (cell_w - 1 - x)
        rows.append(bits)
    return rows

def gen(size):
    fontpath = pick_font()
    try:
        font = ImageFont.truetype(fontpath, size, index=0)
    except Exception:
        font = ImageFont.truetype(fontpath, size)
    cjk_w = size
    ascii_w = max(4, size // 2)
    entries = []
    for ch in sorted(CHARS):
        cp = ord(ch)
        is_wide = cp > 0x2E7F  # rough CJK range
        w = cjk_w if is_wide else ascii_w
        rows = render_char(font, ch, w, size, size)
        rows_txt = ", ".join("0x%04X" % r for r in rows)
        entries.append((cp, w, size, rows_txt))
    return entries, fontpath

def emit(f, name, entries):
    f.write("var %s = map[rune]Glyph{\n" % name)
    for cp, w, h, rows in entries:
        esc = ""
        if cp == 0x27:
            esc = "0x27"
        elif cp == 0x5C:
            esc = "0x5C"
        else:
            esc = "'%s'" % chr(cp) if 32 <= cp < 127 else "0x%04X" % cp
        f.write("\t%s: {W: %d, H: %d, Rows: []uint16{%s}},\n" % (esc, w, h, rows))
    f.write("}\n\n")

def main():
    entries12, path = gen(12)
    entries16, _ = gen(16)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Code generated by gen_font.py; DO NOT EDIT.\n")
        f.write("// Font: %s\n\n" % path)
        f.write("package main\n\n")
        f.write("type Glyph struct {\n\tW, H uint8\n\tRows []uint16\n}\n\n")
        emit(f, "font12", entries12)
        emit(f, "font16", entries16)
    print("wrote %s: %d glyphs (12px) + %d glyphs (16px) from %s" % (OUT, len(entries12), len(entries16), path))

if __name__ == "__main__":
    main()
