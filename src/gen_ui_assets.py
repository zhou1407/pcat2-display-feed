"""Generate font_data.go and icons_data.go for pcat2d.

Run with the bundled DSH Python (Pillow):
  C:\\Users\\LYC-SERVER\\.dsh\\dsh-runtimes\\dsh-primary-runtime\\dependencies\\python\\python.exe gen_ui_assets.py

Fonts: Microsoft YaHei from C:\\Windows\\Fonts\\msyh.ttc at 10/12/16/20 px.
Glyph bitmaps are stored as top-left-anchored rows (bit W-1 = leftmost pixel)
plus a vertical offset from the ascender line, so all sizes share one baseline.
Icons: 1x masks rasterised from the official SVG assets (scratch/goal2/icons/raster).
"""
import io
import os
from PIL import Image, ImageDraw, ImageFont

BASE = os.path.dirname(os.path.abspath(__file__))
WS = os.path.abspath(os.path.join(BASE, "..", "..", ".."))
FONT_PATH = r"C:\Windows\Fonts\msyh.ttc"
RASTER = os.path.join(WS, "scratch", "goal2", "icons", "raster")

SIZES = [10, 12, 16, 20]

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
EXTRA = (
    "电池电压功率剩余请及时充电中接入设备在线第页共台上限连接数率系统"
    "内存风扇板温序列号运行版本时间日期星期未连接已启用禁用开关光定"
    "时关闭网络无线有线信号强度运营商模块型号地址状态数据检测等待无"
    "清零当日每月已用吞吐下行上行接收发送温度转速亮度息屏唤醒设置保"
    "存恢复默认应用正在错误失败成功环形百分比兆吉字节分钟秒伏毫安瓦"
    "微℃°↕↓↑→←·…—"
    "０１２３４５６７８９ＡＢＣ"
)
def scan_source_chars():
    found = ''
    seen = set()
    for name in sorted(os.listdir(BASE)):
        if not name.endswith('.go') or name in ('font_data.go', 'icons_data.go'):
            continue
        src = io.open(os.path.join(BASE, name), encoding='utf-8').read()
        for ch in src:
            if ord(ch) > 0x7f and ch not in seen:
                seen.add(ch)
                found += ch
    return found


CHARS = ''.join(dict.fromkeys(ASCII + EXTRA + scan_source_chars()))


def gen_fonts():
    out = [
        "package main",
        "",
        "// Code generated by gen_ui_assets.py; DO NOT EDIT.",
        "",
        "type Glyph struct {",
        "\tW, H uint8",
        "\tOff  int8",
        "\tRows []uint32",
        "}",
        "",
    ]
    for size in SIZES:
        font = ImageFont.truetype(FONT_PATH, size)
        canvas = Image.new("L", (size * 4, size * 4), 0)
        draw = ImageDraw.Draw(canvas)
        entries = []
        for ch in CHARS:
            if ch in "\n":
                continue
            if ch == " ":
                entries.append((ch, size // 3, 1, 0, [0]))
                continue
            w = 0
            try:
                l, t, r, b = draw.textbbox((0, 0), ch, font=font, anchor="la")
            except Exception:
                continue
            w = r - l
            h = b - t
            if w <= 0 or h <= 0:
                continue
            if w > 31:
                w = 31
            if h > 31:
                h = 31
            canvas.paste(0, (0, 0, canvas.width, canvas.height))
            draw.text((-l, -t), ch, font=font, fill=255, anchor="la")
            rows = []
            for y in range(h):
                bits = 0
                for x in range(w):
                    if canvas.getpixel((x, y)) > 64:
                        bits |= 1 << (w - 1 - x)
                rows.append(bits)
            entries.append((ch, w, h, t, rows))

        var = "font%d" % size
        out.append("var %s = map[rune]Glyph{" % var)
        for ch, w, h, off, rows in entries:
            rs = ", ".join("0x%x" % v for v in rows)
            rune_lit = "0x%04x" % ord(ch)
            out.append(
                "\t%s: {W: %d, H: %d, Off: %d, Rows: []uint32{%s}},"
                % (rune_lit, w, h, off, rs)
            )
        out.append("}")
        out.append("")
    out.append("var fontSizes = []map[rune]Glyph{font10, font12, font16, font20}")
    out.append("")
    with open(os.path.join(BASE, "font_data.go"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote font_data.go")


def gen_icons():
    icons = [("iconEth", "eth.png"), ("iconWifi", "wifi.png")]
    out = [
        "package main",
        "",
        "// Code generated by gen_ui_assets.py; DO NOT EDIT.",
        "",
        "type iconMask struct {",
        "\tW, H int",
        "\tRows []uint32",
        "}",
        "",
    ]
    for var, name in icons:
        path = os.path.join(RASTER, name)
        im = Image.open(path).convert("L")
        w, h = im.size
        rows = []
        for y in range(h):
            bits = 0
            for x in range(w):
                if im.getpixel((x, y)) > 64:
                    bits |= 1 << (w - 1 - x)
            rows.append(bits)
        rs = ", ".join("0x%x" % v for v in rows)
        out.append("var %s = iconMask{W: %d, H: %d, Rows: []uint32{%s}}" % (var, w, h, rs))
        out.append("")
    with open(os.path.join(BASE, "icons_data.go"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote icons_data.go")


if __name__ == "__main__":
    gen_fonts()
    gen_icons()
